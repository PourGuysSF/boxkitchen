-- Plan: docs/inventory-guide.md. Run ONCE, by Stephen, in the Supabase SQL Editor
-- (the source dropdown beside Save must read Database).
--
-- Why: the page lists every NEW order-guide item until a manager gives it a place or
-- taps "Don't count". Without this table, the 56 items left off on purpose would be
-- "new" forever and a genuinely new one would be lost among them.
--
-- Same pattern as Slice 0: RLS on; anon + authenticated may SELECT, INSERT, UPDATE;
-- no delete policy (a decision is undone by active = false, never deleted).
-- One transaction; the check at the end undoes everything unless it matches.

begin;

create table public.inventory_left_off (
  id             bigint generated by default as identity primary key,
  location       text        not null default 'Tempest',
  order_item_id  bigint      not null references public.order_items (id),
  active         boolean     not null default true,
  created_at     timestamptz not null default now()
);
create unique index inventory_left_off_one_active
  on public.inventory_left_off (location, order_item_id) where active = true;

alter table public.inventory_left_off enable row level security;
grant select, insert, update on public.inventory_left_off to anon, authenticated;
create policy inventory_left_off_select on public.inventory_left_off for select to anon, authenticated using (true);
create policy inventory_left_off_insert on public.inventory_left_off for insert to anon, authenticated with check (true);
create policy inventory_left_off_update on public.inventory_left_off for update to anon, authenticated using (true) with check (true);

