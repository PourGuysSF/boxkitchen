declare n int; n_placed int; n_unlisted int;
begin
  select count(*) into n from public.inventory_left_off where location = 'Tempest' and active;
  -- nothing left off may also be on the count
  select count(*) into n_placed from public.inventory_left_off lo
    join public.inventory_items ii on ii.order_item_id = lo.order_item_id and ii.active and ii.location = 'Tempest'
   where lo.active;
  -- every active guide item is now either on the count or left off: nothing is "new"
  select count(*) into n_unlisted from public.order_items o
   where o.location = 'Tempest' and o.active
     and not exists (select 1 from public.inventory_items ii where ii.order_item_id = o.id and ii.active)
     and not exists (select 1 from public.inventory_left_off lo where lo.order_item_id = o.id and lo.active);
  if n <> 56 then raise exception 'expected 56 left-off items, got %', n; end if;
  if n_placed <> 0 then raise exception '% left-off items are also on the count', n_placed; end if;
  if n_unlisted <> 0 then raise exception '% guide items are neither counted nor left off', n_unlisted; end if;
end
$check$;

