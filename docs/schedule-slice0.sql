-- Schedule, Slice 0: tables, security rules, and the Tempest seed.
-- Plan: docs/schedule.md. Run ONCE, by Stephen, in the Supabase SQL editor (source: Database).
--
-- Mirrors the site's existing pattern (as recorded by Inventory Guide Slice 0, 2026-10-06):
--   RLS on; anon + authenticated may SELECT, INSERT, UPDATE; NO delete policy, so rows
--   are never deleted (retire a person with active = false; clear a box with kind = null).
--   Ids are identity columns, every table has `location text default 'Tempest'` (boxes
--   inherit it from their person), and foreign keys name their parents.
--   No phone column anywhere, on purpose: the site and its key are public.
--
-- One transaction: if any step fails, or the checks at the end do not match, NOTHING
-- is kept. The last statement prints the row counts.
--
-- UNDO (only Stephen runs this, and only if he wants the tables gone, children first):
--   drop table public.schedule_shifts, public.schedule_day_notes, public.schedule_standing, public.schedule_people;
