-- 9. Checks. Any mismatch raises an error, and the whole transaction is undone. --------
do $check$
declare n_people int; n_day int; n_night int; n_standing int; n_shifts int; n_notes int;
begin
  select count(*), count(*) filter (where crew = 'day'), count(*) filter (where crew = 'night')
    into n_people, n_day, n_night from public.schedule_people where location = 'Tempest';
  select count(*) into n_standing from public.schedule_standing where location = 'Tempest';
  select count(*) into n_shifts   from public.schedule_shifts;
  select count(*) into n_notes    from public.schedule_day_notes;
  if n_people <> 11 then raise exception 'expected 11 people, got %', n_people; end if;
  if n_day <> 4 then raise exception 'expected 4 day crew, got %', n_day; end if;
  if n_night <> 7 then raise exception 'expected 7 night crew, got %', n_night; end if;
  if n_standing <> 3 then raise exception 'expected 3 standing notes, got %', n_standing; end if;
  if n_shifts <> 0 then raise exception 'expected 0 shifts, got %', n_shifts; end if;
  if n_notes <> 0 then raise exception 'expected 0 day notes, got %', n_notes; end if;
end
$check$;

commit;

