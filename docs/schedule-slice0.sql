begin;

-- 1. People, per location, in the sheet's order within each crew ----------------------
create table public.schedule_people (
  id          bigint generated by default as identity primary key,
  location    text        not null default 'Tempest',
  name        text        not null check (btrim(name) <> ''),
  crew        text        not null check (crew in ('day', 'night')),
  sort_order  integer     not null,
  active      boolean     not null default true,
  created_at  timestamptz not null default now()
);

-- 2. One box per person per day. Empty (kind null) = not scheduled yet, which is not OFF.
create table public.schedule_shifts (
  id          bigint generated by default as identity primary key,
  person_id   bigint      not null references public.schedule_people (id),
  work_date   date        not null,
  kind        text        check (kind in ('shift', 'off', 'request')),
  shift_text  text,
  training    boolean     not null default false,
  updated_at  timestamptz not null default now(),
  created_at  timestamptz not null default now(),
  constraint schedule_shifts_text_matches_kind check (
    -- written so a NULL kind can't slip past (NULL in a check counts as a pass)
    ((kind is not distinct from 'shift') = (shift_text is not null))
    and coalesce(btrim(shift_text) <> '', true)
  ),
  constraint schedule_shifts_training_needs_shift check (not training or kind = 'shift')
);
create unique index schedule_shifts_one_per_day on public.schedule_shifts (person_id, work_date);
comment on column public.schedule_shifts.kind is
  'shift / off / request, or NULL = not scheduled yet (blank is not OFF). Saved by upsert on (person_id, work_date).';
comment on column public.schedule_shifts.shift_text is
  'The shift as written (e.g. 4pm-CL). Text, tidied on save, never parsed into clock times.';

-- 3. Games, parties, conventions: one note per day ------------------------------------
create table public.schedule_day_notes (
  id          bigint generated by default as identity primary key,
  location    text        not null default 'Tempest',
  note_date   date        not null,
  note        text        not null default '',
  updated_at  timestamptz not null default now(),
  created_at  timestamptz not null default now()
);
create unique index schedule_day_notes_one_per_day on public.schedule_day_notes (location, note_date);

-- 4. Notes that repeat every week (trash, compost, janitors) --------------------------
create table public.schedule_standing (
  id          bigint generated by default as identity primary key,
  location    text        not null default 'Tempest',
  label       text        not null check (btrim(label) <> ''),
  weekdays    smallint[]  not null check (cardinality(weekdays) > 0 and weekdays <@ '{0,1,2,3,4,5,6}'::smallint[]),
  sort_order  integer     not null default 1000,
  active      boolean     not null default true,
  created_at  timestamptz not null default now()
);
comment on column public.schedule_standing.weekdays is 'Days it shows: Sunday = 0 … Saturday = 6.';

-- 5. updated_at is set by the database, not by a phone's clock ------------------------
create function public.schedule_touch_updated_at() returns trigger
language plpgsql as $fn$
begin
  new.updated_at := now();
  return new;
end
$fn$;
create trigger schedule_shifts_touch before insert or update on public.schedule_shifts
  for each row execute function public.schedule_touch_updated_at();
create trigger schedule_day_notes_touch before insert or update on public.schedule_day_notes
  for each row execute function public.schedule_touch_updated_at();

-- 6. Security rules (Row Level Security) ----------------------------------------------
alter table public.schedule_people    enable row level security;
alter table public.schedule_shifts    enable row level security;
alter table public.schedule_day_notes enable row level security;
alter table public.schedule_standing  enable row level security;

grant select, insert, update on public.schedule_people, public.schedule_shifts,
  public.schedule_day_notes, public.schedule_standing to anon, authenticated;

create policy schedule_people_select on public.schedule_people for select to anon, authenticated using (true);
create policy schedule_people_insert on public.schedule_people for insert to anon, authenticated with check (true);
create policy schedule_people_update on public.schedule_people for update to anon, authenticated using (true) with check (true);

create policy schedule_shifts_select on public.schedule_shifts for select to anon, authenticated using (true);
create policy schedule_shifts_insert on public.schedule_shifts for insert to anon, authenticated with check (true);
create policy schedule_shifts_update on public.schedule_shifts for update to anon, authenticated using (true) with check (true);

create policy schedule_day_notes_select on public.schedule_day_notes for select to anon, authenticated using (true);
create policy schedule_day_notes_insert on public.schedule_day_notes for insert to anon, authenticated with check (true);
create policy schedule_day_notes_update on public.schedule_day_notes for update to anon, authenticated using (true) with check (true);

create policy schedule_standing_select on public.schedule_standing for select to anon, authenticated using (true);
create policy schedule_standing_insert on public.schedule_standing for insert to anon, authenticated with check (true);
create policy schedule_standing_update on public.schedule_standing for update to anon, authenticated using (true) with check (true);

