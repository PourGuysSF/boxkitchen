-- Recipe Costing (B4.3), Slice 0: four tables and their security rules. No data.
-- Plan: docs/recipe-costing.md. Run ONCE, by Stephen, in the Supabase SQL editor
-- (source dropdown beside Save must read "Database").
--
-- Mirrors the pattern read from pg_policies on 2026-11-02 (plan, Slice 0):
--   RLS on; anon + authenticated may SELECT, INSERT, UPDATE; NO delete policy, so rows
--   are never deleted from the site (dismiss with active = false). bigint identity ids,
--   `location text not null default 'Tempest'`, foreign keys name their parents.
-- "Recipes" and ingredient_costs are NOT altered.
--
-- One transaction: if any step fails, or the check at the end does not match, NOTHING
-- is kept. The last statement prints the row counts (all 0).

begin;

-- 1. One row per linked ingredient line of a recipe. Keyed by the line's own text. ------
create table public.recipe_lines (
  id                  bigint generated by default as identity primary key,
  location            text        not null default 'Tempest',
  recipe_id           bigint      not null references public."Recipes" (id) on delete cascade,
  line_text           text        not null check (length(btrim(line_text)) > 0),
  occurrence          integer     not null default 1 check (occurrence >= 1),
  component           text,
  qty                 numeric,
  unit                text,
  ingredient_cost_id  bigint      references public.ingredient_costs (id),
  sub_recipe_id       bigint      references public."Recipes" (id) on delete restrict,
  skip                boolean     not null default false,
  linked_name         text,
  active              boolean     not null default true,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  constraint recipe_lines_target check (
    (skip and ingredient_cost_id is null and sub_recipe_id is null)
    or (not skip and qty is not null and qty > 0
        and unit is not null and length(btrim(unit)) > 0
        and num_nonnulls(ingredient_cost_id, sub_recipe_id) = 1)
  ),
  constraint recipe_lines_not_itself check (sub_recipe_id is null or sub_recipe_id <> recipe_id)
);
-- FULL unique index (not partial) so PostgREST on_conflict can target it.
create unique index recipe_lines_key on public.recipe_lines (recipe_id, line_text, occurrence);

-- 2. One conversion per price-list row per kind of measure, "as bought". --------------
--    from_kind is 'volume', 'weight', or a count word ('each', 'clove', 'bunch', ...).
create table public.ingredient_conversions (
  id                  bigint generated by default as identity primary key,
  location            text        not null default 'Tempest',
  ingredient_cost_id  bigint      not null references public.ingredient_costs (id),
  from_kind           text        not null check (length(btrim(from_kind)) > 0),
  from_qty            numeric     not null check (from_qty > 0),
  from_unit           text        not null check (length(btrim(from_unit)) > 0),
  to_qty              numeric     not null check (to_qty > 0),
  to_unit             text        not null check (length(btrim(to_unit)) > 0),
  estimate            boolean     not null default false,
  note                text,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);
create unique index ingredient_conversions_key
  on public.ingredient_conversions (ingredient_cost_id, from_kind);

-- 3. A house recipe's own conversions, "as made" (M1). to_unit is in the yield's kind. --
create table public.recipe_conversions (
  id          bigint generated by default as identity primary key,
  location    text        not null default 'Tempest',
  recipe_id   bigint      not null references public."Recipes" (id) on delete cascade,
  from_kind   text        not null check (length(btrim(from_kind)) > 0),
  from_qty    numeric     not null check (from_qty > 0),
  from_unit   text        not null check (length(btrim(from_unit)) > 0),
  to_qty      numeric     not null check (to_qty > 0),
  to_unit     text        not null check (length(btrim(to_unit)) > 0),
  estimate    boolean     not null default false,
  note        text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create unique index recipe_conversions_key on public.recipe_conversions (recipe_id, from_kind);

-- 4. One yield and portion per recipe. Amount and unit come as a pair, or not at all. ---
create table public.recipe_yields (
  id              bigint generated by default as identity primary key,
  location        text        not null default 'Tempest',
  recipe_id       bigint      not null references public."Recipes" (id) on delete cascade,
  yield_qty       numeric     check (yield_qty > 0),
  yield_unit      text,
  yield_estimate  boolean     not null default false,
  portion_qty     numeric     check (portion_qty > 0),
  portion_unit    text,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  constraint recipe_yields_pair check ((yield_qty is null) = (yield_unit is null)),
  constraint recipe_portion_pair check ((portion_qty is null) = (portion_unit is null))
);
create unique index recipe_yields_key on public.recipe_yields (recipe_id);

-- Indexes for the foreign keys the key indexes do not already lead with.
create index recipe_lines_ingredient_cost on public.recipe_lines (ingredient_cost_id);
create index recipe_lines_sub_recipe      on public.recipe_lines (sub_recipe_id);

-- 5. Security: RLS on; select / insert / update; NO delete policy. ---------------------
alter table public.recipe_lines           enable row level security;
alter table public.ingredient_conversions enable row level security;
alter table public.recipe_conversions     enable row level security;
alter table public.recipe_yields          enable row level security;

grant select, insert, update on public.recipe_lines, public.ingredient_conversions,
  public.recipe_conversions, public.recipe_yields to anon, authenticated;

create policy recipe_lines_select on public.recipe_lines for select to anon, authenticated using (true);
create policy recipe_lines_insert on public.recipe_lines for insert to anon, authenticated with check (true);
create policy recipe_lines_update on public.recipe_lines for update to anon, authenticated using (true) with check (true);

create policy ingredient_conversions_select on public.ingredient_conversions for select to anon, authenticated using (true);
create policy ingredient_conversions_insert on public.ingredient_conversions for insert to anon, authenticated with check (true);
create policy ingredient_conversions_update on public.ingredient_conversions for update to anon, authenticated using (true) with check (true);

create policy recipe_conversions_select on public.recipe_conversions for select to anon, authenticated using (true);
create policy recipe_conversions_insert on public.recipe_conversions for insert to anon, authenticated with check (true);
create policy recipe_conversions_update on public.recipe_conversions for update to anon, authenticated using (true) with check (true);

create policy recipe_yields_select on public.recipe_yields for select to anon, authenticated using (true);
create policy recipe_yields_insert on public.recipe_yields for insert to anon, authenticated with check (true);
create policy recipe_yields_update on public.recipe_yields for update to anon, authenticated using (true) with check (true);

-- 6. Check. Any mismatch raises an error, and the whole transaction is undone. ---------
do $check$
declare n_lines int; n_ic int; n_rc int; n_y int; n_pol int; n_del int;
begin
  select count(*) into n_lines from public.recipe_lines;
  select count(*) into n_ic    from public.ingredient_conversions;
  select count(*) into n_rc    from public.recipe_conversions;
  select count(*) into n_y     from public.recipe_yields;
  select count(*) into n_pol from pg_policies where schemaname = 'public'
     and tablename in ('recipe_lines','ingredient_conversions','recipe_conversions','recipe_yields');
  select count(*) into n_del from pg_policies where schemaname = 'public' and cmd in ('DELETE','ALL')
     and tablename in ('recipe_lines','ingredient_conversions','recipe_conversions','recipe_yields');
  if n_lines <> 0 then raise exception $m$expected 0 recipe_lines, got %$m$, n_lines; end if;
  if n_ic    <> 0 then raise exception $m$expected 0 ingredient_conversions, got %$m$, n_ic; end if;
  if n_rc    <> 0 then raise exception $m$expected 0 recipe_conversions, got %$m$, n_rc; end if;
  if n_y     <> 0 then raise exception $m$expected 0 recipe_yields, got %$m$, n_y; end if;
  if n_pol  <> 12 then raise exception $m$expected 12 policies, got %$m$, n_pol; end if;
  if n_del   <> 0 then raise exception $m$expected no delete policy, got %$m$, n_del; end if;
end
$check$;

commit;

-- 7. What you should see: four rows, each 0.
select 'recipe_lines' as table_name, count(*) as row_count from public.recipe_lines
union all select 'ingredient_conversions', count(*) from public.ingredient_conversions
union all select 'recipe_conversions',     count(*) from public.recipe_conversions
union all select 'recipe_yields',          count(*) from public.recipe_yields;
