-- Inventory Guide, Slice 0: tables, security rules, and the Tempest seed.
-- Plan: docs/inventory-guide.md. Run ONCE, by Stephen, in the Supabase SQL editor.
--
-- Mirrors the site's existing pattern, read from pg_policies on 2026-10-06:
--   RLS on; anon + authenticated may SELECT, INSERT, UPDATE; NO delete policy, so rows
--   are never deleted (retire with active = false). Ids are identity columns, every
--   table has `location text default 'Tempest'`, and foreign keys name their parents.
--
-- One transaction: if any step fails, or the checks at the end do not match, NOTHING
-- is kept. The last statement prints the row counts.

begin;

-- 1. Storage places, per location, in walking order -----------------------------------
create table public.inventory_places (
  id          bigint generated by default as identity primary key,
  location    text        not null default 'Tempest',
  label       text        not null,
  sort_order  integer     not null default 1000,
  active      boolean     not null default true,
  created_at  timestamptz not null default now()
);
create unique index inventory_places_loc_label on public.inventory_places (location, label);

-- 2. Which order-guide item is counted where. One item may be in more than one place. --
create table public.inventory_items (
  id             bigint generated by default as identity primary key,
  location       text        not null default 'Tempest',
  order_item_id  bigint      not null references public.order_items (id),
  place_id       bigint      not null references public.inventory_places (id),
  sort_order     integer     not null default 1000,
  active         boolean     not null default true,
  created_at     timestamptz not null default now()
);
create unique index inventory_items_one_active_per_place
  on public.inventory_items (place_id, order_item_id) where active = true;

-- 3. One count per month. Only one may be open at a time. -----------------------------
create table public.inventory_counts (
  id          bigint generated by default as identity primary key,
  location    text        not null default 'Tempest',
  period      date        not null check (extract(day from period) = 1),
  status      text        not null default 'open' check (status in ('open', 'closed')),
  closed_at   timestamptz,
  closed_by   text,
  created_at  timestamptz not null default now()
);
create unique index inventory_counts_one_per_month on public.inventory_counts (location, period);
create unique index inventory_counts_one_open on public.inventory_counts (location) where status = 'open';
comment on column public.inventory_counts.period is
  'First day of the month this count closes out: 2026-10-01 = the October month-end count.';

-- 4. What was counted: one row per item-in-a-place, per month. -------------------------
create table public.inventory_count_lines (
  id                 bigint generated by default as identity primary key,
  location           text        not null default 'Tempest',
  count_id           bigint      not null references public.inventory_counts (id),
  inventory_item_id  bigint      not null references public.inventory_items (id),
  full_qty           numeric     check (full_qty >= 0),
  loose_qty          numeric     check (loose_qty >= 0),
  pack_qty_snap      numeric,
  pack_unit_snap     text,
  counted_by         text,
  unit_cost_frozen   numeric,
  value_frozen       numeric,
  value_note         text        check (value_note in ('no price', 'pack changed', 'order units')),
  updated_at         timestamptz not null default now(),
  created_at         timestamptz not null default now()
);
create unique index inventory_count_lines_one_per_item
  on public.inventory_count_lines (count_id, inventory_item_id);
comment on column public.inventory_count_lines.full_qty is
  'Full packs. Both full_qty and loose_qty null = not counted (blank is not zero).';
comment on column public.inventory_count_lines.pack_qty_snap is
  'The price-list pack this line was counted against (e.g. 40). NULL = counted in order-guide units, before the item had a pack; pack_unit_snap then holds that order unit.';
comment on column public.inventory_count_lines.pack_unit_snap is
  'Unit of loose_qty (e.g. lb) at the time of counting, or the order-guide unit when pack_qty_snap is NULL.';
comment on column public.inventory_count_lines.value_frozen is
  'Written at close, from the price list as it stood that day. NULL with a value_note = not valued, never $0.';

-- 5. Close and reopen history. Append-only: no update policy. --------------------------
create table public.inventory_count_log (
  id          bigint generated by default as identity primary key,
  location    text        not null default 'Tempest',
  count_id    bigint      not null references public.inventory_counts (id),
  action      text        not null check (action in ('start', 'close', 'reopen')),
  by_name     text,
  created_at  timestamptz not null default now()
);

-- 6. Security rules (Row Level Security) ----------------------------------------------
alter table public.inventory_places      enable row level security;
alter table public.inventory_items       enable row level security;
alter table public.inventory_counts      enable row level security;
alter table public.inventory_count_lines enable row level security;
alter table public.inventory_count_log   enable row level security;

grant select, insert, update on public.inventory_places, public.inventory_items,
  public.inventory_counts, public.inventory_count_lines to anon, authenticated;
grant select, insert on public.inventory_count_log to anon, authenticated;

create policy inventory_places_select on public.inventory_places for select to anon, authenticated using (true);
create policy inventory_places_insert on public.inventory_places for insert to anon, authenticated with check (true);
create policy inventory_places_update on public.inventory_places for update to anon, authenticated using (true) with check (true);

create policy inventory_items_select on public.inventory_items for select to anon, authenticated using (true);
create policy inventory_items_insert on public.inventory_items for insert to anon, authenticated with check (true);
create policy inventory_items_update on public.inventory_items for update to anon, authenticated using (true) with check (true);

create policy inventory_counts_select on public.inventory_counts for select to anon, authenticated using (true);
create policy inventory_counts_insert on public.inventory_counts for insert to anon, authenticated with check (true);
create policy inventory_counts_update on public.inventory_counts for update to anon, authenticated using (true) with check (true);

-- The freeze: a count line can be added or changed only while its month is open.
create policy inventory_count_lines_select on public.inventory_count_lines for select to anon, authenticated using (true);
create policy inventory_count_lines_insert on public.inventory_count_lines for insert to anon, authenticated
  with check (exists (select 1 from public.inventory_counts c
                      where c.id = inventory_count_lines.count_id and c.status = 'open'));
create policy inventory_count_lines_update on public.inventory_count_lines for update to anon, authenticated
  using      (exists (select 1 from public.inventory_counts c
                      where c.id = inventory_count_lines.count_id and c.status = 'open'))
  with check (exists (select 1 from public.inventory_counts c
                      where c.id = inventory_count_lines.count_id and c.status = 'open'));

create policy inventory_count_log_select on public.inventory_count_log for select to anon, authenticated using (true);
create policy inventory_count_log_insert on public.inventory_count_log for insert to anon, authenticated with check (true);

