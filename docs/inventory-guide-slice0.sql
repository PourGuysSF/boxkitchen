-- 9. Checks. Any mismatch raises an error, and the whole transaction is undone. --------
do $check$
declare n_places int; n_items int; n_distinct int; n_bad int;
begin
  select count(*) into n_places from public.inventory_places where location = 'Tempest';
  select count(*), count(distinct order_item_id) into n_items, n_distinct
    from public.inventory_items where location = 'Tempest';
  select count(*) into n_bad
    from public.inventory_items ii join public.order_items o on o.id = ii.order_item_id
   where ii.location = 'Tempest' and (o.active is not true or o.location is distinct from 'Tempest');
  if n_places <> 10 then raise exception 'expected 10 places, got %', n_places; end if;
  if n_items <> 216 then raise exception 'expected 216 item-in-place rows, got %', n_items; end if;
  if n_distinct <> 198 then raise exception 'expected 198 distinct items, got %', n_distinct; end if;
  if n_bad <> 0 then raise exception '% seeded items are not active Tempest order-guide items', n_bad; end if;
end
$check$;

commit;

